def seed_bot_chat(
    build: fc.BuildInfo,
    paths: fc.InstancePaths,
    profile: str,
    session_id: str,
    *,
    messages: list[dict[str, str]] | None = None,
) -> None:
    messages = messages if messages is not None else [
        {"role": "user", "content": "fixture seed: hello"},
        {"role": "assistant", "content": "fixture seed: hi there"},
    ]
    tmp_dir = paths.out_dir / "direct_send_seed"
    tmp_dir.mkdir(parents=True, exist_ok=True)
    messages_file = tmp_dir / f"{profile}-{session_id}-bot-chat.json"
    messages_file.write_text(json.dumps(messages), encoding="utf-8")
    fc.run_seed_script(
        build,
        FIXTURE_SEED,
        "seed-session",
        "--home", str(paths.home),
        "--profile", profile,
        "--session-id", session_id,
        "--source", "desktop",
        "--title", BOT_CHAT_TITLE,
        "--hidden",
        "--messages-file", str(messages_file),
    )


