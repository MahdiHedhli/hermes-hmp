#!/usr/bin/env python3
"""Fixture-gateway helper for F2 direct-send integration tests (`HMP_V1.md` §7a, T-N015/T-N016).

Builds on `build_fixture.py`'s OFFLINE build (`--build <label> --out <dir>`, run unmodified as a
subprocess -- exactly like `server/tests/integration/test_reads_fixture.py`'s own `_build()`
helper; this module never imports `build_fixture.py`, so nothing here can regress F1's own fixture
tests) and ADDS, without touching that module or its output format:

  - a canonical "Bot Chat" session per profile (`fixture_seed.py seed-session --title "Bot Chat"
    --hidden`, already supports both flags -- no `fixture_seed.py` change needed);
  - `platforms.api_server` enabled on the DEFAULT profile's own `config.yaml`, bound to
    `127.0.0.1` on a fresh free port, with a synthetic >=16-char key inline (`extra.key` --
    `bridge.direct_send_endpoint`'s own DEFAULT-profile precedence, review round 2 should-fix);
  - a deterministic loopback model: the Hermes source tree's OWN e2e fixture,
    `tests/fakes/fake_llm_provider.py` (a real, stdlib-only HTTP server speaking the OpenAI Chat
    Completions wire format), loaded directly from the target BUILD's own `src_dir` via
    `importlib` (never a real provider, never a real network call) and run IN-PROCESS as a
    context manager, so every "reply" this suite ever sees is exactly `default_text` -- fully
    deterministic, per this task's own requirement.

This module owns its OWN gateway `--serve` equivalent (`start_gateway`, mirroring
`build_fixture.py`'s `serve_instances` for the HMP listener alone) rather than calling
`build_fixture.py --serve`: that function REWRITES `config.yaml` from scratch on every serve
(`_write_config_yaml(paths, profile_names, port=port)`) and would silently discard the
api_server/model blocks this module just wrote. One fixture gateway runs at a time (host load,
mirroring `test_reads_fixture.py`'s own convention) -- callers are responsible for not starting a
second one concurrently.

Everything here is additive test tooling: `fixture_seed.py`/`fixture_pairing_cli.py` are called
unmodified, through the SAME `_fixture_common.py` helpers `build_fixture.py` itself uses.
"""

